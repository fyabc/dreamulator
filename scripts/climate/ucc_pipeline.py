#!/usr/bin/env python3
"""One-command regeneration of every UCC derived asset.

The UCC surface has two kinds of derived product, each already with its own
generator; this orchestrator chains them per target so a profile change, a
canon-data change (e.g. the GCM downscaling entering canon) or a fixture
refresh is one command instead of a remembered sequence:

- ``climate_yearly.msgpack`` per planet map dir — per-cell UCC descriptors and
  classification.  Engine worlds regenerate through
  ``regen_climate_yearly.py`` (dequantizes the persisted monthly series, no
  rebuild); the earth root through ``scripts/earth/export_earth_yearly.py``
  (``data_source: observation``); the solar bodies through
  ``import_solar_common.write_ucc_yearly`` on their persisted monthly (labels
  summarised here, full import provenance in each importer — that file stays
  the single source of truth for them).
- ``docs/ucc/examples/*-data.md`` — the worked-example fixtures generated by
  ``ucc_obs_descriptors.py`` + ``ucc_examples_earth.py`` (earth),
  ``ucc_examples_nacrea.py`` (nacrea, read from the climate-canon branch) and
  ``ucc_examples_solar.py`` (mars/venus/titan/moon).

After running, the audit compares each yearly's mtime against its monthly and
each fixture's 生成日期 against its yearly, and exits non-zero on anything
stale — the same check runs report-only with ``--plan``.

Usage:
    uv run python scripts/climate/ucc_pipeline.py --plan      # actions + audit
    uv run python scripts/climate/ucc_pipeline.py             # regenerate all
    uv run python scripts/climate/ucc_pipeline.py --only fixtures,nacrea
    uv run python scripts/climate/ucc_pipeline.py --all      # + QA baselines
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]

#: The climate-canon branch for nacrea (design-notes 0013); the nacrea fixture
#: and yearly read from it, not the engine-climate root.
NACREA_CANON_BRANCH = "gcm-t42-712"


@dataclass(frozen=True)
class RegenTarget:
    """One ``climate_yearly.msgpack`` to regenerate."""

    label: str
    map_dir: Path
    kind: str  # "engine" | "earth_obs" | "solar_obs"
    regen_args: list[str] | None = None  # engine: subprocess args for regen
    data_source: str | None = None  # solar_obs: payload data_source label
    provenance_note: str | None = None  # solar_obs: provenance summary
    optional: bool = False  # included only with --all


def _engine(
    label: str,
    world: str,
    planet: str,
    branch: str | None = None,
    climate_source: str | None = None,
    optional: bool = False,
) -> RegenTarget:
    args = [
        sys.executable,
        str(_ROOT / "scripts/climate/regen_climate_yearly.py"),
        world,
        "--planet",
        planet,
    ]
    if branch:
        args += ["--branch", branch]
    if climate_source:
        args += ["--climate-source", climate_source]
    base = Path("data/worlds") / world
    sub = base / "branches" / branch if branch else base
    map_dir = sub / "maps" / planet
    return RegenTarget(label, _ROOT / map_dir, "engine", regen_args=args, optional=optional)


def _solar(body: str, planet_id: str, data_source: str, note: str) -> RegenTarget:
    map_dir = _ROOT / "data/worlds/earth/maps" / planet_id
    return RegenTarget(
        f"earth/{planet_id}", map_dir, "solar_obs", data_source=data_source, provenance_note=note
    )


def yearly_targets(*, all_targets: bool) -> list[RegenTarget]:
    targets = [
        _engine("nacrea (root, engine climate)", "nacrea", "satellite_nacrea"),
        _engine(
            f"nacrea/{NACREA_CANON_BRANCH} (climate canon)",
            "nacrea",
            "satellite_nacrea",
            branch=NACREA_CANON_BRANCH,
            climate_source=f"gcm pack import ({NACREA_CANON_BRANCH})",
        ),
        _engine("myworld/planet_gaia", "myworld", "planet_gaia"),
        _engine("earth/climate-dev", "earth", "planet_earth", branch="climate-dev"),
        RegenTarget(
            "earth/planet_earth", _ROOT / "data/worlds/earth/maps/planet_earth", "earth_obs"
        ),
        _solar(
            "mars",
            "planet_mars",
            "gcm-climatology",
            "MCD diurnal-mean Ls-bin climatology (import_mars.py)",
        ),
        _solar(
            "venus",
            "planet_venus",
            "gcm-climatology",
            "VCD tsurf surface climatology (import_venus.py)",
        ),
        _solar(
            "titan",
            "satellite_titan",
            "gcm-climatology",
            "TAM tsurf/precip Titan-year bins (import_titan.py)",
        ),
        _solar(
            "moon", "satellite_moon", "observation", "LRO Diviner bolometric GCP (import_moon.py)"
        ),
    ]
    if all_targets:
        for extra in ("_b3", "_baseline", "_baselineA", "_baseline_oro"):
            targets.append(
                _engine(
                    f"earth/climate-dev/{extra}",
                    "earth",
                    extra,
                    branch="climate-dev",
                    optional=True,
                )
            )
        for bridge in sorted(
            p.parent.name
            for p in (_ROOT / "data/worlds/earth/branches").glob("bridge-*/maps/*")
            if p.is_dir()
        ):
            planets = sorted(
                q.name
                for q in (_ROOT / "data/worlds/earth/branches" / bridge / "maps").iterdir()
                if q.is_dir()
            )
            for planet in planets:
                targets.append(
                    _engine(
                        f"earth/{bridge}/{planet}", "earth", planet, branch=bridge, optional=True
                    )
                )
    return targets


@dataclass(frozen=True)
class FixtureTarget:
    label: str
    out: Path
    steps: list[list[str]]  # subprocess argv list, in order
    yearly_dep: Path  # the yearly whose freshness the fixture must match


def fixture_targets() -> list[FixtureTarget]:
    py = sys.executable
    ucc = _ROOT / "docs/ucc/examples"
    nacrea_canon_map = (
        _ROOT / "data/worlds/nacrea/branches" / NACREA_CANON_BRANCH / "maps/satellite_nacrea"
    )
    return [
        FixtureTarget(
            "fixture earth",
            ucc / "earth-data.md",
            [
                [py, str(_ROOT / "scripts/climate/ucc_obs_descriptors.py")],
                [py, str(_ROOT / "scripts/climate/ucc_examples_earth.py")],
            ],
            _ROOT / "data/worlds/earth/maps/planet_earth/climate_yearly.msgpack",
        ),
        FixtureTarget(
            f"fixture nacrea ({NACREA_CANON_BRANCH})",
            ucc / "nacrea-data.md",
            [
                [
                    py,
                    str(_ROOT / "scripts/climate/ucc_examples_nacrea.py"),
                    "--map-dir",
                    str(nacrea_canon_map),
                ]
            ],
            nacrea_canon_map / "climate_yearly.msgpack",
        ),
        *(
            FixtureTarget(
                f"fixture {body}",
                ucc / f"{body}-data.md",
                [[py, str(_ROOT / "scripts/solar/ucc_examples_solar.py"), "--planet", body]],
                _ROOT / "data/worlds/earth/maps" / planet_id / "climate_yearly.msgpack",
            )
            for body, planet_id in (
                ("mars", "planet_mars"),
                ("venus", "planet_venus"),
                ("titan", "satellite_titan"),
                ("moon", "satellite_moon"),
            )
        ),
    ]


def _run(argv: list[str], *, plan: bool) -> None:
    printable = " ".join(str(a) for a in argv[1:])  # drop the python exe
    print(f"  $ {printable}")
    if plan:
        return
    proc = subprocess.run(argv, cwd=_ROOT)
    if proc.returncode != 0:
        raise SystemExit(f"step failed ({proc.returncode}): {printable}")


def _solar_regen(target: RegenTarget, *, plan: bool) -> None:
    """Recompute one solar body's yearly from its persisted monthly in-process."""
    from dreamulator.import_solar_common import write_ucc_yearly

    monthly = target.map_dir / "climate_monthly.msgpack"
    print(f"  write_ucc_yearly({target.map_dir.relative_to(_ROOT)})")
    if plan:
        return
    if not monthly.exists():
        raise SystemExit(f"missing persisted monthly for {target.label}: {monthly}")
    write_ucc_yearly(
        target.map_dir,
        data_source=target.data_source or "observation",
        provenance={
            "note": (
                f"regenerated from the persisted climate_monthly.msgpack under the "
                f"current UCC profile; import provenance: {target.provenance_note}"
            ),
        },
    )


def _fixture_date(path: Path) -> float:
    """The 生成日期 line's date as a mtime-comparable timestamp (0 when absent)."""
    if not path.exists():
        return 0.0
    head = path.read_text(encoding="utf-8", errors="replace")[:2000]
    m = re.search(r"生成日期[:：]\s*(\d{4})-(\d{2})-(\d{2})", head)
    if not m:
        return 0.0
    import datetime as _dt

    d = _dt.datetime(int(m[1]), int(m[2]), int(m[3])).timestamp()
    return d


def audit(*, all_targets: bool) -> int:
    """Print the freshness table; return the number of stale entries."""
    stale = 0
    print("\nAudit (yearly vs monthly, fixture vs yearly):")
    for t in yearly_targets(all_targets=all_targets):
        if t.optional and not all_targets:
            continue
        yearly = t.map_dir / "climate_yearly.msgpack"
        monthly = t.map_dir / "climate_monthly.msgpack"
        if not yearly.exists():
            print(f"  [MISSING yearly] {t.label}")
            stale += 1
            continue
        if monthly.exists() and yearly.stat().st_mtime < monthly.stat().st_mtime:
            print(f"  [STALE yearly < monthly] {t.label}")
            stale += 1
    for f in fixture_targets():
        ym = f.yearly_dep.stat().st_mtime if f.yearly_dep.exists() else 0.0
        fd = _fixture_date(f.out)
        if fd + 86_400 < ym:  # fixture dated before its yearly's last write
            print(f"  [STALE fixture < yearly] {f.label}")
            stale += 1
    if stale == 0:
        print("  all fresh")
    return stale


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", action="store_true", help="list actions + audit, run nothing")
    parser.add_argument(
        "--only",
        default=None,
        help="comma-separated subset: engine, earth, solar, fixtures, nacrea",
    )
    parser.add_argument("--all", action="store_true", help="include QA baselines and bridge-*")
    args = parser.parse_args()
    only = set(args.only.split(",")) if args.only else {"engine", "earth", "solar", "fixtures"}

    print("UCC pipeline — yearly regenerations:")
    for t in yearly_targets(all_targets=args.all):
        if t.optional and not args.all:
            continue
        if (
            t.kind == "engine"
            and "engine" not in only
            and not ("nacrea" in only and t.label.startswith("nacrea"))
        ):
            continue
        if t.kind == "earth_obs" and "earth" not in only:
            continue
        if t.kind == "solar_obs" and "solar" not in only:
            continue
        if t.kind == "engine":
            assert t.regen_args is not None
            _run(t.regen_args, plan=args.plan)
        elif t.kind == "earth_obs":
            _run(
                [
                    sys.executable,
                    str(_ROOT / "scripts/earth/export_earth_yearly.py"),
                    "--output-dir",
                    str(t.map_dir),
                ],
                plan=args.plan,
            )
        else:
            _solar_regen(t, plan=args.plan)

    if "fixtures" in only or "nacrea" in only or "earth" in only or "solar" in only:
        print("\nFixtures:")
        for f in fixture_targets():
            if "fixtures" not in only and not (
                ("nacrea" in only and f.label.startswith("fixture nacrea"))
                or ("earth" in only and f.label == "fixture earth")
                or ("solar" in only and f.label.split()[-1] in {"mars", "venus", "titan", "moon"})
            ):
                continue
            for step in f.steps:
                _run(step, plan=args.plan)

    stale = audit(all_targets=args.all)
    if stale:
        print(f"\n{stale} stale entr{'y is' if stale == 1 else 'ies are'} listed above.")
        if not args.plan:
            raise SystemExit(1)


if __name__ == "__main__":
    main()
